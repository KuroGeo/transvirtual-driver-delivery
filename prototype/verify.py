def source_distance(stop):
    lat1,lat2=math.radians(driver['latitude']),math.radians(stop['latitude'])
    longitude_delta=math.radians(stop['longitude']-driver['longitude'])
    cosine=math.sin(lat1)*math.sin(lat2)+math.cos(lat1)*math.cos(lat2)*math.cos(longitude_delta)
    return 6371000*math.acos(max(-1,min(1,cosine)))
